#!/bin/sh
# Сколько ядер занято работой — прямо, а не через время выполнения.
#
# Время выполнения отвечает на вопрос косвенно: в нём сидят и накладные
# расходы на fork, и работа фона, и они на плате оказались не малы (цикл в
# форкнутом процессе стоит заметно дороже, чем тот же цикл в самом шелле).
# Здесь считается другое: сколько процессорного времени система потратила за
# секунду реального.  На одном ядре это единица по построению, на четырёх —
# столько, сколько их работает.
#
# Счётчик берётся из /proc/<pid>/psinfo.  На aarch64 ядро считает его через
# CNTVCT_EL0, а он у всех ядер один и идёт с одной частотой, поэтому
# суммировать по процессам законно.
#
# СКЛАДЫВАТЬ НАДО ТРИ ПОЛЯ, А НЕ ОДНО.  Первая версия брала только десятое —
# `cycles`, собственное время процесса, — а время, которое ядро потратило на
# его IPC и на его системные вызовы, лежит отдельно, в одиннадцатом и
# двенадцатом (`minix/fs/procfs/pid.c`, `pid_psinfo`).  Пропуск этих двух не
# просто занижает результат: доля, попадающая в них, растёт с числом
# процессов, то есть занижает тем сильнее, чем выше нагрузка — а это ровно та
# форма, которую принимает мнимый потолок.  Числа вехи 8.0.3 сняты старой
# версией и потому пересняты.
#
# Печатается и сумма по всем процессам, и сумма по одним задачам.  Разница
# между ними — фон, и он здесь не мал: чтение /proc/[0-9]*/psinfo само по
# себе работа для VFS и procfs, и её тем больше, чем больше процессов.  То
# есть замер меряет отчасти сам себя, и увидеть это можно только когда обе
# суммы стоят рядом.
#
#	smpocc.sh [итераций] [окно, с]

ITERS=${1:-100000}
W=${2:-4}

# Все процессы: собственные циклы плюс ядерные IPC и вызовы.
sum() { cat /proc/[0-9]*/psinfo 2>/dev/null |
	awk '{ s += $10 + $11 + $12 } END { printf "%.0f\n", s }'; }

# Одни только счётные задачи.  Они называются sh, как и породивший их шелл, —
# но шелл в окне спит на sleep и почти ничего не считает.
sumjobs() { cat /proc/[0-9]*/psinfo 2>/dev/null |
	awk '$4 == "sh" { s += $10 + $11 + $12 } END { printf "%.0f\n", s }'; }

now()  { awk '{print $1}' /proc/uptime; }

occ() {			# occ <сколько задач>
	j=0
	while [ $j -lt $1 ]; do
		( n=0; while [ $n -lt $ITERS ]; do n=$((n + 1)); done ) &
		j=$((j + 1))
	done
	# Окно берётся в середине, когда все задачи уже бегут.
	sleep 2
	c0=$(sum); k0=$(sumjobs); t0=$(now)
	sleep $W
	c1=$(sum); k1=$(sumjobs); t1=$(now)
	wait
	awk -v c0="$c0" -v c1="$c1" -v k0="$k0" -v k1="$k1" \
	    -v a="$t0" -v b="$t1" -v j="$1" \
	    'BEGIN { printf "%2d jobs: всего %12.0f cyc/s, задачи %12.0f cyc/s (окно %.2f s)\n", \
		     j, (c1 - c0) / (b - a), (k1 - k0) / (b - a), b - a }'
}

occ 1
occ 2
occ 3
occ 4
occ 6
occ 8
