/*
trng.h

Аппаратный источник случайного, если он у машины есть.
*/

#ifndef TRNG_H
#define TRNG_H

/*
 * Найти генератор в дереве устройств, отобразить его регистры и засыпать
 * первую порцию в пул. OK - источник есть; ENODEV - машина без него, и это
 * штатный ответ, а не отказ.
 */
int trng_init(void);

/*
 * Подсыпать ещё, если источник есть. Молчит и ничего не делает, если его
 * нет. Возвращает число отданных в пул байт.
 */
size_t trng_feed(void);

#endif /* TRNG_H */
