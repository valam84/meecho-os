#!/bin/sh
# Занятость ядер по kern.cp_time: тики по состояниям, которые ядро ведёт само
# на каждое ядро (user, nice, sys, intr, idle), сумма по машине.
#
# Не суммой cycles из psinfo (smpocc.sh): то лишь собственное время процесса,
# и снимок стоит дороже измеряемого (CLAUDE.md, SMP). Нагрузка — awk, а не
# шелловский цикл: тот почти весь в ядре и системных процессах.
#
# Доли, а не «сколько ядер»: простаивающее ядро останавливает таймер, и
# абсолютный счёт тиков за окно врёт. На четырёх ядрах с восемью задачами
# ждать около трёх четвертей в user (так было 2026-09-09); с одной задачей —
# около четверти.
#
#	smpcp.sh [задач] [итераций]
PATH=$PATH:/sbin:/usr/sbin
j=${1:-8}
n=${2:-20000000}

cpt() { sysctl kern.cp_time | tr -c '0-9\n' ' ' | awk '{print $1, $2, $3, $4, $5}'; }
now() { awk '{print $1}' /proc/uptime; }

a=$(cpt); t0=$(now)
i=0
while [ $i -lt $j ]; do
	awk -v n="$n" 'BEGIN { for (k = 0; k < n; k++) s += k }' &
	i=$((i + 1))
done
wait
b=$(cpt); t1=$(now)

echo "$a $b $t0 $t1" | awk -v j="$j" '{
	u = ($6 - $1) + ($7 - $2); s = $8 - $3; r = $9 - $4; d = $10 - $5
	t = u + s + r + d
	if (t <= 0) { print "smpcp: kern.cp_time did not move"; exit 1 }
	printf "jobs %d  %.2f s  user %.1f%%  sys %.1f%%  intr %.1f%%  idle %.1f%%\n",
	    j, $12 - $11, 100 * u / t, 100 * s / t, 100 * r / t, 100 * d / t
}'
