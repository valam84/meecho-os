#!/bin/sh
# 8.0.3: работают ли четыре ядра платы под нагрузкой.
#
# Меряется не «поднялись ли» (это видно по /proc/cpuinfo), а делают ли они
# работу: N одинаковых счётных циклов запускаются одновременно, и время берёт
# сама система из /proc/uptime.  Если ядро одно, N циклов стоят N времён
# одного; если четыре — примерно столько же, сколько один, пока N не
# превысит число ядер.
#
# Последовательный прогон тех же N циклов подряд снимается тем же кодом и
# служит опорой: он показывает, сколько эта работа стоит без параллелизма на
# этой самой машине в эту самую минуту, а не по памяти о прошлом прогоне.
#
#	smpload.sh [итераций]

ITERS=${1:-60000}

now() { awk '{print $1}' /proc/uptime; }

# Один счётный цикл.  Тело намеренно самое простое, какое есть в шелле: цель
# — занять процессор, ничего не спрашивая ни у ядра, ни у диска.
spin() {
	n=0
	while [ $n -lt $1 ]; do n=$((n+1)); done
}

par() {			# par <сколько> — столько циклов одновременно
	t0=$(now)
	j=0
	while [ $j -lt $1 ]; do
		spin "$ITERS" &
		j=$((j + 1))
	done
	wait
	t1=$(now)
	awk -v a="$t0" -v b="$t1" -v j="$1" \
	    'BEGIN { printf "%2d parallel: %6.2f s\n", j, b - a }'
}

seq_() {		# seq_ <сколько> — столько циклов подряд
	t0=$(now)
	j=0
	while [ $j -lt $1 ]; do
		spin "$ITERS"
		j=$((j + 1))
	done
	t1=$(now)
	awk -v a="$t0" -v b="$t1" -v j="$1" \
	    'BEGIN { printf "%2d serial:   %6.2f s\n", j, b - a }'
}

echo "iterations per cycle: $ITERS"
grep -c processor /proc/cpuinfo 2>/dev/null | sed 's/^/cpus in cpuinfo: /'

par 1
par 2
par 3
par 4
par 8
seq_ 4
par 3
par 4
par 1
