#!/bin/sh
# Смешанная нагрузка: не только счёт, но и обращения к файловой системе.
#
# Счётный цикл живёт целиком в пользовательском пространстве и о ядре не
# спрашивает ничего.  Обход дерева спрашивает постоянно, и каждый его вопрос
# проходит через VFS, MFS и драйвер eMMC, то есть через большой замок ядра —
# ровно то место, которое на четырёх настоящих ядрах ни разу не работало.
# Здесь важно не время, а то, что система переживает такую нагрузку и что
# ответы совпадают: каждый обход печатает, сколько файлов он насчитал.
#
#	smpio.sh [сколько задач] [сколько кругов]

JOBS=${1:-4}
ROUNDS=${2:-3}

now() { awk '{print $1}' /proc/uptime; }

walk() {		# один обход дерева, печатает своё число файлов
	k=0
	while [ $k -lt $ROUNDS ]; do
		find /usr /bin /sbin /etc -type f 2>/dev/null | wc -l
		k=$((k + 1))
	done
}

t0=$(now)
j=0
while [ $j -lt $JOBS ]; do
	walk > /tmp/walk.$j 2>&1 &
	j=$((j + 1))
done
wait
t1=$(now)

awk -v a="$t0" -v b="$t1" -v j="$JOBS" -v r="$ROUNDS" \
    'BEGIN { printf "%d jobs x %d walks: %.2f s\n", j, r, b - a }'

# Все обходы обязаны насчитать одно и то же — иначе под конкуренцией
# теряются записи каталогов, а это уже не про скорость.
cat /tmp/walk.* | sort -u | sed 's/^/files seen: /'
rm -f /tmp/walk.*
