#!/usr/bin/env python3
"""Hardware tables of the SDM660 from the Linux sources, as C headers.

	gen-sdm660-tables.py LINUX_TREE OUT_DIR

Writes OUT_DIR/sdm660_tlmm.h and OUT_DIR/sdm660_gcc.h: facts about the
silicon - which TLMM tile each GPIO is in and what its mux functions are,
and for every GCC branch clock the device tree can name, its registers.
Taken from drivers/pinctrl/qcom/pinctrl-sdm660.c, drivers/clk/qcom/
gcc-sdm660.c and include/dt-bindings/clock/qcom,gcc-sdm660.h of
github.com/sdm660-mainline/linux.  Numbers and names only - no code is
carried over.  Regenerate rather than edit.
"""
import re, sys

tree, out = sys.argv[1], sys.argv[2]

# --- TLMM -----------------------------------------------------------------
pc = open(tree + "/drivers/pinctrl/qcom/pinctrl-sdm660.c").read()
pins = {}
for m in re.finditer(r"^\s*PINGROUP\((\d+),\s*(\w+),([^)]*)\)", pc, re.M):
    n, tile = int(m.group(1)), m.group(2)
    funcs = [f.strip() for f in m.group(3).split(",")]
    assert len(funcs) == 9, (n, funcs)
    pins[n] = (tile, funcs)
npins = max(pins) + 1
assert sorted(pins) == list(range(npins)), "gap in the GPIO table"
tiles = {"SOUTH": 0, "CENTER": 1, "NORTH": 2}

with open(out + "/sdm660_tlmm.h", "w") as f:
    f.write("/* Generated by port/clover/gen-sdm660-tables.py from "
            "pinctrl-sdm660.c. Do not edit. */\n")
    f.write("#define SDM660_NGPIO\t%d\n" % npins)
    f.write("/* Tiles, as the TLMM node's reg-names call them. */\n")
    f.write('static const char *const sdm660_tile_name[] = '
            '{ "south", "center", "north" };\n')
    f.write("/* Per GPIO: its tile, and mux functions 1..9 (0 is gpio). */\n")
    f.write("static const struct { unsigned char tile; "
            "const char *func[9]; } sdm660_gpio[SDM660_NGPIO] = {\n")
    for n in range(npins):
        tile, funcs = pins[n]
        fs = ", ".join('"%s"' % x if x != "_" else "NULL" for x in funcs)
        f.write("\t/* %3d */ { %d, { %s } },\n" % (n, tiles[tile], fs))
    f.write("};\n")

# --- GCC ------------------------------------------------------------------
gc = open(tree + "/drivers/clk/qcom/gcc-sdm660.c").read()
ids = {}
for m in re.finditer(r"#define\s+(GCC_\w+)\s+(\d+)",
                     open(tree + "/include/dt-bindings/clock/"
                          "qcom,gcc-sdm660.h").read()):
    ids[m.group(1)] = int(m.group(2))

rcgs = {}
for m in re.finditer(r"static struct clk_rcg2 (\w+) = \{(.*?)\n\};", gc,
                     re.S):
    c = re.search(r"\.cmd_rcgr\s*=\s*(0x[0-9a-f]+)", m.group(2))
    if c:
        rcgs[m.group(1)] = int(c.group(1), 16)

branches = {}
for m in re.finditer(r"static struct clk_branch (\w+) = \{(.*?)\n\};", gc,
                     re.S):
    body = m.group(2)
    halt = re.search(r"\.halt_reg\s*=\s*(0x[0-9a-f]+)", body)
    en = re.search(r"\.enable_reg\s*=\s*(0x[0-9a-f]+)", body)
    mask = re.search(r"\.enable_mask\s*=\s*BIT\((\d+)\)", body)
    check = re.search(r"\.halt_check\s*=\s*(\w+)", body)
    par = re.search(r"&(\w+)\.clkr\.hw", body)
    if not (en and mask):
        continue
    branches[m.group(1)] = (
        int(halt.group(1), 16) if halt else 0,
        int(en.group(1), 16), int(mask.group(1)),
        check.group(1) if check else "BRANCH_HALT",
        rcgs.get(par.group(1), 0) if par else 0)

table = []
for m in re.finditer(r"\[(GCC_\w+)\]\s*=\s*&(\w+)\.clkr", gc):
    name, var = m.group(1), m.group(2)
    if var in branches and name in ids:
        table.append((ids[name], name) + branches[var])
table.sort()

with open(out + "/sdm660_gcc.h", "w") as f:
    f.write("/* Generated by port/clover/gen-sdm660-tables.py from "
            "gcc-sdm660.c and qcom,gcc-sdm660.h. Do not edit. */\n")
    f.write("/*\n * Per branch clock, by its device tree number: the CBCR "
            "(status), the\n * enable register and bit, whether the enable is "
            "a vote (BRANCH_HALT_VOTED)\n * or the CBCR's own bit 0, whether "
            "the status may be checked at all, and\n * the CMD_RCGR of the "
            "root it hangs off (0: none of its own).\n */\n")
    f.write("static const struct { unsigned short id; unsigned int halt, en;"
            " unsigned char bit, voted, nocheck; unsigned int rcg; "
            "const char *name; } sdm660_gcc[] = {\n")
    for (i, name, halt, en, bit, check, rcg) in table:
        voted = 1 if check == "BRANCH_HALT_VOTED" else 0
        nocheck = 1 if check in ("BRANCH_HALT_SKIP", "BRANCH_HALT_DELAY")\
            else 0
        f.write('\t{ %3d, 0x%05x, 0x%05x, %2d, %d, %d, 0x%05x, "%s" },\n'
                % (i, halt, en, bit, voted, nocheck, rcg, name))
    f.write("};\n")
print("tlmm: %d gpios; gcc: %d branch clocks" % (npins, len(table)))
